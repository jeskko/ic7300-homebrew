int hb_text(hb_canvas *c, int x, int y, const char *s, int scale, hb_color color)
{
    int x0 = x;
    for (; *s; s++, x += HB_FONT_ADVANCE * scale) {
        int ch = *s >= 'a' && *s <= 'z' ? *s - 'a' + 'A' : *s;
        if (ch < FIRST || ch > LAST)
            ch = '?';
        const uint8_t *g = g_font[ch - FIRST];
        for (int row = 0; row < HB_FONT_H; row++)
            for (int col = 0; col < HB_FONT_W; col++)
                if (g[row] & (0x10 >> col))
                    hb_fill_rect(c, x + col * scale, y + row * scale, scale, scale, color);
    }
    return x - x0;
}

int hb_text_width(const char *s, int scale)
{
    int n = 0;
    while (*s++)
        n++;
    return n * HB_FONT_ADVANCE * scale;
}
